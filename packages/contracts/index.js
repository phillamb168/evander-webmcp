/** Evander's public read-only tool bridge contract. This is not MCP JSON-RPC. */
export const VERSION = '1.0';
export const TOOL_PATHS = Object.freeze({ manifest: '/evander-webmcp/v1/tools', call: '/evander-webmcp/v1/call' });
export const validPath = path => typeof path === 'string' && path.length <= 2048 && /^\/(?!\/)[^?#\s\\]*$/.test(path) && !path.split('/').includes('..');
export const isRecord = value => value !== null && typeof value === 'object' && !Array.isArray(value);

export function validateManifest(value) {
  if (!isRecord(value) || (value.version !== undefined && value.version !== VERSION) || !Array.isArray(value.tools) || value.tools.length > 30) throw new Error('Invalid tool manifest');
  const names = new Set();
  for (const tool of value.tools) {
    if (!isRecord(tool) || typeof tool.name !== 'string' || !/^[a-zA-Z][\w-]{0,63}$/.test(tool.name) || names.has(tool.name) || tool.name === 'evander_respond' || tool.name === 'evander_navigate' || !isRecord(tool.inputSchema) || tool.inputSchema.type !== 'object') throw new Error('Invalid tool descriptor');
    names.add(tool.name);
  }
  return value;
}

export function validateEnvelope(value) {
  if (!isRecord(value) || (value.version !== undefined && value.version !== VERSION) || !isRecord(value.result)) throw new Error('Invalid tool response');
  const result = value.result;
  if (result.status !== undefined && !['ok', 'unavailable', 'stale', 'already_read'].includes(result.status)) throw new Error('Invalid result status');
  for (const key of ['chunks', 'results', 'links', 'items', 'omissions']) if (result[key] !== undefined && !Array.isArray(result[key])) throw new Error(`Invalid result ${key}`);
  if (result.coverage !== undefined && !['complete', 'partial', 'unavailable'].includes(result.coverage)) throw new Error('Invalid coverage');
  return value;
}

export async function boundedJson(response, limit = 180000) {
  if (!response.ok) throw new Error(`Upstream HTTP ${response.status}`);
  if (!response.body) throw new Error('Missing response body');
  const reader = response.body.getReader(); const parts = []; let size = 0;
  try {
    while (true) {
      const { done, value } = await reader.read(); if (done) break;
      size += value.byteLength; if (size > limit) throw new Error('Response limit'); parts.push(value);
    }
    const bytes = new Uint8Array(size); let offset = 0;
    for (const part of parts) { bytes.set(part, offset); offset += part.byteLength; }
    return JSON.parse(new TextDecoder('utf-8', { fatal: true }).decode(bytes));
  } finally { await reader.cancel().catch(() => {}); }
}

export function publicUrl(value, base) {
  if (typeof value !== 'string' || !value.trim() || /[\u0000-\u0020\\]/.test(value)) return null;
  try { const url = new URL(value, base); return ['http:', 'https:'].includes(url.protocol) && !url.username && !url.password ? url.href : null; } catch { return null; }
}

/** Trusted deployment data, never generated by a model or accepted from a request. */
export function createRouteMap({ sourceOrigin, publicOrigin, routes }) {
  for (const origin of [sourceOrigin, publicOrigin]) if (!publicUrl(origin) || new URL(origin).origin !== origin) throw new Error('Route map requires exact origins');
  if (!Array.isArray(routes) || routes.length > 10000) throw new Error('Invalid route map');
  const byPublic = new Map(), bySource = new Map();
  for (const route of routes) {
    if (!isRecord(route) || !validPath(route.path) || !validPath(route.sourcePath) || byPublic.has(route.path)) throw new Error('Invalid or duplicate route');
    if (route.sourceAliases !== undefined && !Array.isArray(route.sourceAliases)) throw new Error('Invalid source aliases');
    if (route.anchors !== undefined && (!isRecord(route.anchors) || Object.entries(route.anchors).some(([key, val]) => !/^#[^\s#]+$/.test(key) || typeof val !== 'string' || !/^#[^\s#]+$/.test(val)))) throw new Error('Invalid anchor map');
    byPublic.set(route.path, route);
    for (const path of [route.sourcePath, ...(route.sourceAliases ?? [])]) {
      if (!validPath(path) || bySource.has(path)) throw new Error('Invalid or duplicate source path');
      bySource.set(path, route);
    }
  }
  return Object.freeze({
    sourceOrigin, publicOrigin,
    resolveCurrentPath(path) { return byPublic.get(path)?.sourcePath ?? null; },
    mapSourceUrl(value) {
      const safe = publicUrl(value, sourceOrigin); if (!safe) return null;
      const url = new URL(safe), route = url.origin === sourceOrigin ? bySource.get(url.pathname) : null;
      if (!route || url.search) return safe;
      const hash = url.hash ? route.anchors?.[url.hash] ?? (route.preserveAnchors ? url.hash : null) : '';
      if (hash === null) return safe;
      return publicOrigin + route.path + hash;
    },
  });
}

